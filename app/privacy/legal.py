def _html_page(title: str, body_text: str) -> str:
    paragraphs = "\n".join(
        f"<p>{escape(line)}</p>" if line.strip() else ""
        for line in body_text.splitlines()
    )
    return f"""<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{escape(title)}</title>
<style>
body{{font-family:system-ui,-apple-system,sans-serif;max-width:820px;margin:40px auto;padding:0 20px;line-height:1.55}}
h1{{font-size:28px}}p{{white-space:pre-wrap}}input,button{{font:inherit;padding:10px;margin:6px 0;width:100%;box-sizing:border-box}}
button{{cursor:pointer}}.status{{margin-top:12px}}
</style>
</head><body><h1>{escape(title)}</h1>{paragraphs}</body></html>"""


